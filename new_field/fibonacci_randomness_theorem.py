def compare_to_other_sequences(modulus: int = 256, length: int = 1000):
    """
    Compare Fibonacci to other deterministic sequences.
    """
    print("=" * 80)
    print(f"COMPARISON: Fibonacci vs Other Sequences (mod {modulus})")
    print("=" * 80)
    print()

    estimator = KolmogorovComplexityEstimator()

    sequences = {}

    # Fibonacci
    fib = [0, 1]
    for i in range(2, length):
        fib.append((fib[i-1] + fib[i-2]) % modulus)
    sequences['Fibonacci'] = bytes(fib[:length])

    # Tribonacci (F(n) = F(n-1) + F(n-2) + F(n-3))
    trib = [0, 0, 1]
    for i in range(3, length):
        trib.append((trib[i-1] + trib[i-2] + trib[i-3]) % modulus)
    sequences['Tribonacci'] = bytes(trib[:length])

    # Lucas sequence (same recurrence, different initial conditions)
    lucas = [2, 1]
    for i in range(2, length):
        lucas.append((lucas[i-1] + lucas[i-2]) % modulus)
    sequences['Lucas'] = bytes(lucas[:length])

    # Powers of 2
    powers = [(2**i) % modulus for i in range(length)]
    sequences['Powers of 2'] = bytes(powers)

    # Arithmetic
    arith = [(7*i) % modulus for i in range(length)]
    sequences['Arithmetic'] = bytes(arith)

    # Random
    np.random.seed(42)
    random_seq = np.random.randint(0, modulus, length, dtype=np.uint8)
    sequences['Random'] = random_seq.tobytes()

    results = []
    for name, data in sequences.items():
        complexity = estimator.normalized_complexity(data)
        is_random = estimator.algorithmic_randomness_test(data)

        results.append((name, complexity, is_random))
        print(f"{name:15s}: complexity={complexity:.3f}, random={is_random}")

    print()
    print("OBSERVATION:")
    print()

    # Find sequences with complexity > 0.9
    high_complexity = [name for name, c, _ in results if c > 0.9]
    print(f"Sequences with complexity > 0.9 (appear random):")
    for name in high_complexity:
        print(f"  - {name}")
    print()

    return results


