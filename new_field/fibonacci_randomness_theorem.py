def compute_pisano_period(n: int, max_period: int = 100000) -> int:
    """
    Compute the Pisano period π(n) - the period of Fibonacci mod n.

    The Pisano period is the smallest k such that:
    F(k) ≡ 0 (mod n) and F(k+1) ≡ 1 (mod n)
    """
    if n == 1:
        return 1

    a, b = 0, 1
    for i in range(1, max_period):
        a, b = b, (a + b) % n
        if a == 0 and b == 1:
            return i

    return -1  # Period too large


def analyze_fibonacci_randomness(moduli: list[int], sequence_length: int = 1000):
    """
    Analyze how random Fibonacci sequences appear for different moduli.

    HYPOTHESIS: Larger Pisano periods → more random appearance
    """
    print("=" * 80)
    print("FIBONACCI RANDOMNESS ANALYSIS")
    print("=" * 80)
    print()

    estimator = KolmogorovComplexityEstimator()
    results = []

    for m in moduli:
        # Generate Fibonacci mod m
        fib = [0, 1]
        for i in range(2, sequence_length):
            fib.append((fib[i-1] + fib[i-2]) % m)

        # Map to bytes range [0, 255] for compression
        if m <= 256:
            data = bytes(fib[:sequence_length])
        else:
            # Scale to [0, 255] range
            scaled = [int((f * 256) / m) for f in fib[:sequence_length]]
            data = bytes(scaled)

        # Compute properties
        pisano = compute_pisano_period(m)
        complexity = estimator.normalized_complexity(data)
        is_random = estimator.algorithmic_randomness_test(data)

        # Compute actual entropy
        unique_values = len(set(fib[:sequence_length]))
        empirical_entropy = unique_values / m if m > 0 else 0

        results.append({
            'modulus': m,
            'pisano_period': pisano,
            'normalized_complexity': complexity,
            'appears_random': is_random,
            'unique_values': unique_values,
            'empirical_entropy': empirical_entropy
        })

        print(f"Modulus {m:4d}: π={pisano:6d}, K/n={complexity:.3f}, "
              f"random={is_random}, unique={unique_values}/{m}")

    return results


